import {spawn,execFileSync} from 'node:child_process';
import {readFile,writeFile,appendFile,mkdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
const requireApi=createRequire(resolve('apps/api/package.json'));
const privateEnvironment=requireApi('dotenv').parse(await readFile('/Users/dingshinn/.codex/worktrees/step-02-coding/rpg-maker-maker/.env'));
const directory=process.env['STEP03_EVIDENCE_DIR']??'.local/step03-development';
const [label,expectedText,command,...args]=process.argv.slice(2), expected=Number(expectedText);
await mkdir(directory,{recursive:true}); const start=Date.now();
const environment={...process.env,DATABASE_URL:privateEnvironment.DATABASE_URL,API_PORT:'4314',WEB_PORT:'5176',INTEGRATION_API_PORT:'4314'};
const child=spawn(command,args,{env:environment,stdio:['ignore','pipe','pipe']});
let output='';for(const pipe of [child.stdout,child.stderr])pipe.on('data',bytes=>{output+=bytes.toString();process.stdout.write(bytes);});
const exitCode=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',resolve);});
if(output.includes(privateEnvironment.DATABASE_URL))throw Error('Unsafe output: private connection string must not be archived.');
const log=resolve(directory,label+'.log');await writeFile(log,output,{flag:'wx'});
const sha=createHash('sha256').update(output).digest('hex');
await appendFile(resolve(directory,'commands.jsonl'),JSON.stringify({label,command,args,commit:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),dirty:!!execFileSync('git',['status','--porcelain'],{encoding:'utf8'}).trim(),environment:{API_PORT:'4314',WEB_PORT:'5176',INTEGRATION_API_PORT:'4314',E2E_MODE:process.env['E2E_MODE']??null,database:'owned-loopback-55432-private-credentials'},expectedExit:expected,exitCode,durationMs:Date.now()-start,logSha256:sha})+'\n');
process.exitCode=exitCode===expected?0:1;

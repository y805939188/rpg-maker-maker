import { describe,it,expect } from 'vitest';
import { validateNativeEmptyPlugins } from '../scripts/prototype-input.js';

// Literal format of the installed MZ 1.10.0 empty newdata/plugins.js, observed independently.
const native = '// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n];\n';
describe('Native MZ editor plugin-list file',()=>{
  it('accepts the exact native empty-list serialization',()=>{
    expect(()=>validateNativeEmptyPlugins(Buffer.from(native))).not.toThrow();
  });
  it('rejects the previous runtime-valid inline file reported unreadable by the editor',()=>{
    expect(()=>validateNativeEmptyPlugins(Buffer.from('// Native compatibility test: no plugins\nvar $plugins = [];\n'))).toThrow(/multiline format/);
  });
  it('rejects nonempty plugin lists so no template plugin is silently enabled',()=>{
    expect(()=>validateNativeEmptyPlugins(Buffer.from(native.replace('[\n]','[{"name":"Other","status":true}]')))).toThrow(/empty plugin list/);
  });
  it('rejects malformed plugin JSON and appended executable code',()=>{
    expect(()=>validateNativeEmptyPlugins(Buffer.from(native.replace('[\n]','[broken]')))).toThrow(/invalid plugin array/);
    expect(()=>validateNativeEmptyPlugins(Buffer.from(native+'runOtherCode();\n'))).toThrow(/multiline format/);
  });
});
